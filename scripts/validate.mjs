// Offline validation harness (AGENTS.md T10). Deterministic: fixed evaluation date, synthetic profile,
// no network. Compares the current engine with the recorded V5.3 baseline and, where the owner has
// pre-registered human labels, against those labels.
//   reports/validation-<date>.csv   one row per vacancy x engine
//   reports/validation-<date>.md    summary, confusion matrix (when labels exist), disagreements
// Human labels live in fixtures/validation-22.labels.json and must be committed BEFORE running this.
import fs from 'node:fs';
import crypto from 'node:crypto';
import {evaluate,ENGINE_VERSION} from '../src/engine/evaluate.mjs';

const EVALUATION_DATE='2026-10-21';
const root=new URL('../',import.meta.url),load=f=>JSON.parse(fs.readFileSync(new URL(f,root),'utf8'));
const jobs=load('fixtures/validation-22.json'),profile=load('fixtures/synthetic-profile.json'),baseline=load('fixtures/baseline-v53.json');
const labelFile=new URL('fixtures/validation-22.labels.json',root);
const labels=fs.existsSync(labelFile)?load('fixtures/validation-22.labels.json').labels||{}:{};
const sha=s=>crypto.createHash('sha256').update(s).digest('hex');
for(const j of jobs)if(sha(j.description)!==j.description_sha256)throw Error(`Fixture text changed: ${j.id}`);

// Human labels use the human-review vocabulary: apply | skip | investigate.
const LABELS=['apply','investigate','skip'];
const toLabel=decision=>decision==='Skip'?'skip':decision==='Apply'||decision==='Apply with tailoring'?'apply':'investigate';
const rows=jobs.map(j=>{
 const r=evaluate({profile:profile.text,vacancy:j,preferences:{salaryFloor:0,minContractMonths:0},evaluationDate:EVALUATION_DATE});
 const old=baseline.find(x=>x.id===j.id)?.v53||{};
 const human=labels[j.id]?.label||j.human_label||null;
 return {id:j.id,title:j.title,human,current:{engine:ENGINE_VERSION,fit_score:r.fit_score,band:r.band,decision:r.decision,confidence:r.confidence.label,eligibility:r.eligibility.status,critical_gaps:r.critical_evidence_gaps.filter(g=>g.severity==='critical').map(g=>g.label),reasons:r.decision_reason},baseline:{engine:'5.3',fit_score:old.fit_score??null,decision:old.decision??null}};
});

const q=x=>'"'+String(x??'').replaceAll('"','""')+'"';
const csv=[['id','title','engine','eligibility','fit_score','band','decision','confidence','critical_gaps','human_label','reasons'].join(',')];
for(const r of rows){
 csv.push([r.id,r.title,r.current.engine,r.current.eligibility,r.current.fit_score,r.current.band,r.current.decision,r.current.confidence,r.current.critical_gaps.join('; '),r.human,r.current.reasons].map(q).join(','));
 csv.push([r.id,r.title,r.baseline.engine,'',r.baseline.fit_score,'',r.baseline.decision,'','',r.human,'recorded baseline'].map(q).join(','));
}

const labelled=rows.filter(r=>LABELS.includes(r.human));
const count=k=>Object.entries(rows.reduce((m,r)=>(m[r.current[k]]=(m[r.current[k]]||0)+1,m),{})).sort().map(([v,n])=>`${v}: ${n}`).join(' · ');
let md=`# Validation report — ${EVALUATION_DATE}\n\nEngine ${ENGINE_VERSION} on ${rows.length} frozen adverts (fixtures/validation-22.json), synthetic profile \`${profile.id}\`, no salary or contract floor. Generated by \`npm run validate\`; byte-identical on re-run.\n\n`;
md+=`## Decisions\n\n${count('decision')}\n\n## Human labels\n\n`;
if(!labelled.length){
 md+=`**0 of ${rows.length} adverts carry a pre-registered human label.** No accuracy, agreement or confusion matrix can be reported. Fill in \`fixtures/validation-22.labels.json\` (template: \`fixtures/validation-22.labels.template.json\`), commit it, then re-run.\n`;
}else{
 const matrix=Object.fromEntries(LABELS.map(h=>[h,Object.fromEntries(LABELS.map(e=>[e,0]))]));
 for(const r of labelled)matrix[r.human][toLabel(r.current.decision)]++;
 const agree=labelled.filter(r=>r.human===toLabel(r.current.decision)).length;
 md+=`${labelled.length} of ${rows.length} labelled. Agreement: ${agree}/${labelled.length}.\n\n| human \\ engine | ${LABELS.join(' | ')} |\n|---|${LABELS.map(()=>'---').join('|')}|\n`;
 for(const h of LABELS)md+=`| ${h} | ${LABELS.map(e=>matrix[h][e]).join(' | ')} |\n`;
 md+='\n## Disagreements\n\n'+(labelled.filter(r=>r.human!==toLabel(r.current.decision)).map(r=>`- **${r.id}** ${r.title}: human \`${r.human}\`, engine \`${r.current.decision}\` (${r.current.fit_score??'unrated'}). ${r.current.reasons}`).join('\n')||'None.')+'\n';
}
md+=`\n## Invariants\n\n- Skip with a numeric score: ${rows.filter(r=>r.current.decision==='Skip'&&r.current.fit_score!==null).length}\n- Apply with Low confidence: ${rows.filter(r=>r.current.decision==='Apply'&&r.current.confidence==='Low').length}\n\nScores are evidenced requirement coverage, not hiring probabilities.\n`;

fs.mkdirSync(new URL('reports/',root),{recursive:true});
fs.writeFileSync(new URL(`reports/validation-${EVALUATION_DATE}.csv`,root),csv.join('\n')+'\n');
fs.writeFileSync(new URL(`reports/validation-${EVALUATION_DATE}.md`,root),md);
console.log(md);
