// Deterministic build: src/ -> dist/.
//  dist/index.html                 final page (release stamped)
//  dist/server/index.js            worker entry
//  dist/server/static-assets.mjs   generated map of browser-served files
//  dist/server/app/...             server-side modules, copied byte-for-byte from src/
//  dist/drizzle/, dist/.openai/    database migrations and hosting configuration
// No string templates are spliced into JavaScript: assets are embedded with JSON.stringify only.
import {readFileSync,writeFileSync,mkdirSync,rmSync,cpSync,readdirSync,copyFileSync} from 'node:fs';
import {join,relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {RELEASE} from '../src/version.mjs';

const root=fileURLToPath(new URL('..',import.meta.url));
const src=p=>join(root,'src',p),dist=p=>join(root,'dist',p);
const read=p=>readFileSync(p,'utf8');
const list=dir=>readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?list(join(dir,e.name)):[join(dir,e.name)]).sort();
const stamp=text=>text.replace(/__RELEASE__/g,()=>RELEASE);

const JS='text/javascript; charset=utf-8';
const NO_STORE='no-store';
// Browser-served files: URL path mirrors the src/ layout (web/ is the site root).
const served=[
 ['/index.html',src('web/index.html'),'text/html; charset=utf-8',NO_STORE],
 ['/app.js',src('web/app.js'),JS,NO_STORE],
 ...list(src('web/clients')).map(f=>['/clients/'+relative(src('web/clients'),f),f,JS,NO_STORE]),
 ...list(src('engine')).map(f=>['/engine/'+relative(src('engine'),f),f,JS,NO_STORE]),
 ...list(src('profile')).map(f=>['/profile/'+relative(src('profile'),f),f,JS,f.endsWith('esco-expansion.mjs')?'public, max-age=86400':NO_STORE]),
 ['/vacancies/unified-search.mjs',src('vacancies/unified-search.mjs'),JS,NO_STORE],
 ['/vacancies/shortlist.mjs',src('vacancies/shortlist.mjs'),JS,NO_STORE]
];

rmSync(dist(''),{recursive:true,force:true});
mkdirSync(dist('server/app'),{recursive:true});

const assets={};
for(const [path,file,type,cache] of served){
 const body=path==='/index.html'?stamp(read(file)):read(file);
 assets[path]={body,type,cache};
}
writeFileSync(dist('index.html'),assets['/index.html'].body);
writeFileSync(dist('server/static-assets.mjs'),
 '// GENERATED by scripts/build.mjs from src/. Do not edit.\n'+
 'export default Object.freeze('+JSON.stringify(assets,null,1)+');\n');

for(const part of ['server','vacancies','version.mjs'])cpSync(src(part),dist('server/app/'+part),{recursive:true});
writeFileSync(dist('server/index.js'),
 '// GENERATED by scripts/build.mjs. Worker entry.\n'+
 "import assets from './static-assets.mjs';\n"+
 "import {createWorker} from './app/server/worker.mjs';\n"+
 'export default createWorker(assets);\n');

mkdirSync(dist('drizzle/meta'),{recursive:true});
for(const f of readdirSync(join(root,'drizzle')).filter(f=>f.endsWith('.sql')).sort())copyFileSync(join(root,'drizzle',f),dist('drizzle/'+f));
copyFileSync(join(root,'drizzle/meta/_journal.json'),dist('drizzle/meta/_journal.json'));
mkdirSync(dist('.openai'),{recursive:true});
copyFileSync(join(root,'.openai/hosting.json'),dist('.openai/hosting.json'));

console.log(`Career Radar ${RELEASE} built: ${Object.keys(assets).length} browser assets`);
